// @ts-check
// Builds src/lib/domain/setSymbols.js: TCGdex set id → the set's file name on pokesymbols.com,
// for its symbol (TCGdex's own symbol images don't load) and its logo (TCGdex has few Italian
// ones). Matches the English set names; the few that differ are listed below. The images stay on
// pokesymbols and load at runtime.
//
// Usage: node scripts/set-symbols.mjs   (run again when new sets come out)
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

/** TCGdex ids whose name differs from pokesymbols'. */
const OVERRIDES = {
  'tk-dp-l': 'diamond-and-pearl-trainer-kit-lucario',
  'tk-dp-m': 'diamond-and-pearl-trainer-kit-manaphy',
  hgss1: 'heartgold-soulsilver',
  hgss2: 'unleashed',
  hgss3: 'undaunted',
  hgss4: 'triumphant',
  'tk-bw-e': 'black-and-white-trainer-kit-excadrill',
  'tk-bw-z': 'black-and-white-trainer-kit-zoroark',
  'tk-sm-l': 'sun-and-moon-trainer-kit-lycanroc',
  'tk-sm-r': 'sun-and-moon-trainer-kit-raichu',
  fut2020: 'fustal-promos',
  sve: 'scarlet-and-violet-energies',
  svp: '_promo',
  '30th-c': '30th-celebration',
};

/** @param {string} s */
const norm = (s) =>
  s
    .normalize('NFKD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/&/g, 'and')
    .replace(/pokemon/g, '')
    .replace(/[^a-z0-9]+/g, '');

const html = (await (await fetch('https://pokesymbols.com/tcg/sets')).text()).replace(/\\"/g, '"').replace(/\\u0026/g, '&');
/** @type {Map<string, string>} */
const byName = new Map();
for (const m of html.matchAll(/\{"imageSrc":"\/images\/tcg\/sets\/symbols\/([^"]+)\.png","url":"[^"]+","name":"([^"]+)"/g)) {
  byName.set(norm(m[2]), m[1]);
}

/** @type {{ id: string, name: string }[]} */
const sets = await (await fetch('https://api.tcgdex.net/v2/en/sets')).json();
/** @type {Record<string, string>} */
const map = {};
for (const s of sets) {
  const slug = OVERRIDES[/** @type {keyof typeof OVERRIDES} */ (s.id)] ?? byName.get(norm(s.name));
  if (slug) map[s.id] = slug;
}

// Not every set has a logo on pokesymbols (trainer kits, promos, McDonald's): check them.
const slugs = [...new Set(Object.values(map))];
const logos = (
  await Promise.all(
    slugs.map(async (slug) => ((await fetch(`https://pokesymbols.com/images/tcg/sets/logos/${slug}.png`, { method: 'HEAD' })).ok ? slug : null)),
  )
)
  .filter(Boolean)
  .sort();

const out = `// @ts-check
// Generated by scripts/set-symbols.mjs: TCGdex set id → set symbol on pokesymbols.com.
/** @type {Record<string, string>} */
export const SET_SYMBOLS = ${JSON.stringify(map, null, 2)};

/** Sets whose logo pokesymbols has. */
const LOGOS = new Set(${JSON.stringify(logos)});

/** Set symbol image (loaded from pokesymbols.com, cached by the app), or null. @param {string} setId */
export const setSymbolUrl = (setId) => (SET_SYMBOLS[setId] ? \`https://pokesymbols.com/images/tcg/sets/symbols/\${SET_SYMBOLS[setId]}.png\` : null);

/**
 * Set logo: TCGdex's in the card language when it has one (few Italian ones), else the English
 * one from pokesymbols.com, else null (show the name).
 * @param {string} setId
 * @param {string | null | undefined} [localLogo] TCGdex \`logo\` of the set in the card language
 */
export function setLogoUrl(setId, localLogo) {
  if (localLogo) return \`\${localLogo}.png\`;
  const slug = SET_SYMBOLS[setId];
  return slug && LOGOS.has(slug) ? \`https://pokesymbols.com/images/tcg/sets/logos/\${slug}.png\` : null;
}
`;
writeFileSync(resolve(import.meta.dirname, '../src/lib/domain/setSymbols.js'), out);
console.log(`${Object.keys(map).length} of ${sets.length} sets have a symbol, ${logos.length} a logo`);
